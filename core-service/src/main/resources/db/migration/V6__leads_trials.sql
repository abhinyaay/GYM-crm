-- =====================================================================================
-- Sales pipeline: leads (prospects), follow-up activities and free / paid trials.
-- =====================================================================================
CREATE TABLE leads (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id           bigint       NOT NULL REFERENCES gym_branches (id),
    first_name          varchar(80)  NOT NULL,
    last_name           varchar(80),
    email               varchar(254),
    phone               varchar(20)  NOT NULL,
    source              varchar(20)  NOT NULL
        CHECK (source IN ('WALK_IN', 'WEBSITE', 'INSTAGRAM', 'FACEBOOK', 'GOOGLE', 'REFERRAL', 'PHONE', 'CORPORATE', 'OTHER')),
    interest            varchar(20)  NOT NULL DEFAULT 'MEMBERSHIP'
        CHECK (interest IN ('MEMBERSHIP', 'PERSONAL_TRAINING', 'CLASSES', 'CORPORATE')),
    status              varchar(20)  NOT NULL DEFAULT 'NEW'
        CHECK (status IN ('NEW', 'CONTACTED', 'TOUR_SCHEDULED', 'TRIAL_ACTIVE', 'CONVERTED', 'LOST')),
    owner_user_id       bigint REFERENCES users (id),
    next_follow_up_at   timestamptz,
    trial_subscription_id bigint REFERENCES subscriptions (id),
    trial_ends_on       date,
    member_id           bigint REFERENCES members (id),     -- set when a trial starts or on conversion
    converted_at        timestamptz,
    lost_reason         varchar(30)
        CHECK (lost_reason IS NULL OR lost_reason IN ('PRICE', 'LOCATION', 'TIMING', 'COMPETITOR', 'NOT_INTERESTED', 'UNREACHABLE', 'OTHER')),
    notes               varchar(1000),
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    created_by          bigint,
    updated_by          bigint,
    version             bigint       NOT NULL DEFAULT 0,
    CHECK ((status = 'LOST') = (lost_reason IS NOT NULL)),
    CHECK ((status = 'CONVERTED') = (converted_at IS NOT NULL))
);
-- one open lead per phone number per branch (duplicate enquiries attach to the existing lead)
CREATE UNIQUE INDEX ux_leads_open_phone ON leads (branch_id, phone) WHERE status NOT IN ('CONVERTED', 'LOST');
CREATE INDEX ix_leads_branch_status ON leads (branch_id, status);
CREATE INDEX ix_leads_follow_up ON leads (owner_user_id, next_follow_up_at) WHERE status NOT IN ('CONVERTED', 'LOST');
CREATE INDEX ix_leads_member ON leads (member_id);

CREATE TABLE lead_activities (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lead_id       bigint        NOT NULL REFERENCES leads (id) ON DELETE CASCADE,
    type          varchar(20)   NOT NULL
        CHECK (type IN ('NOTE', 'CALL', 'EMAIL', 'WHATSAPP', 'SMS', 'VISIT', 'TOUR', 'STATUS_CHANGE', 'FOLLOW_UP')),
    body          varchar(2000) NOT NULL,
    due_at        timestamptz,                  -- for FOLLOW_UP tasks
    completed_at  timestamptz,
    created_by    bigint REFERENCES users (id),
    created_at    timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX ix_lead_activities_lead ON lead_activities (lead_id, created_at DESC);
CREATE INDEX ix_lead_activities_due ON lead_activities (due_at) WHERE type = 'FOLLOW_UP' AND completed_at IS NULL;
