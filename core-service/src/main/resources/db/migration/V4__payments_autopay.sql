-- =====================================================================================
-- Payments v2: more methods, saved payment methods (tokens), hosted checkout intents,
-- payment-provider webhooks, store credit, and recurring billing (autopay) with dunning.
-- No card numbers or UPI PINs are ever stored: only provider tokens and display metadata.
-- =====================================================================================

-- ---------------------------------------------------------------- saved payment methods
CREATE TABLE saved_payment_methods (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id            bigint        NOT NULL REFERENCES members (id),
    provider             varchar(20)   NOT NULL CHECK (provider IN ('SIMULATED', 'RAZORPAY')),
    type                 varchar(20)   NOT NULL CHECK (type IN ('CARD', 'UPI')),
    provider_customer_id varchar(100),
    provider_token       varchar(200)  NOT NULL,          -- provider token id (never a PAN)
    brand                varchar(30),                     -- e.g. Visa / Mastercard / RuPay
    last4                varchar(4),
    exp_month            smallint CHECK (exp_month IS NULL OR exp_month BETWEEN 1 AND 12),
    exp_year             smallint,
    vpa_masked           varchar(100),                    -- e.g. as***@okhdfc
    label                varchar(100)  NOT NULL,
    is_default           boolean       NOT NULL DEFAULT false,
    status               varchar(20)   NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'REVOKED', 'EXPIRED')),
    mandate_status       varchar(20)   NOT NULL DEFAULT 'NONE'
        CHECK (mandate_status IN ('NONE', 'PENDING', 'ACTIVE', 'PAUSED', 'REVOKED')),
    mandate_max_amount   numeric(12, 2) CHECK (mandate_max_amount IS NULL OR mandate_max_amount > 0),
    mandate_expires_at   date,
    created_at           timestamptz   NOT NULL DEFAULT now(),
    updated_at           timestamptz   NOT NULL DEFAULT now(),
    created_by           bigint,
    updated_by           bigint,
    revoked_at           timestamptz,
    version              bigint        NOT NULL DEFAULT 0,
    CHECK ((mandate_status = 'NONE') = (mandate_max_amount IS NULL) OR mandate_status = 'REVOKED')
);
CREATE UNIQUE INDEX ux_payment_method_token ON saved_payment_methods (provider, provider_token);
CREATE UNIQUE INDEX ux_payment_method_one_default ON saved_payment_methods (member_id) WHERE is_default AND status = 'ACTIVE';
CREATE INDEX ix_payment_methods_member ON saved_payment_methods (member_id, status);

-- ---------------------------------------------------------------- payments: methods & provider metadata
ALTER TABLE payments DROP CONSTRAINT payments_method_check;
ALTER TABLE payments ADD CONSTRAINT payments_method_check
    CHECK (method IN ('CASH', 'CARD', 'UPI', 'BANK_TRANSFER', 'NET_BANKING', 'WALLET', 'EMI', 'STORE_CREDIT'));
ALTER TABLE payments ADD COLUMN provider varchar(20) NOT NULL DEFAULT 'SIMULATED'
    CHECK (provider IN ('OFFLINE', 'INTERNAL', 'SIMULATED', 'RAZORPAY'));
UPDATE payments SET provider = 'OFFLINE' WHERE method IN ('CASH', 'BANK_TRANSFER');
ALTER TABLE payments ADD COLUMN instrument varchar(120);              -- display text, e.g. "Visa •••• 4242"
ALTER TABLE payments ADD COLUMN emi_tenure_months integer CHECK (emi_tenure_months IS NULL OR emi_tenure_months IN (3, 6, 9, 12));
ALTER TABLE payments ADD COLUMN payment_method_id bigint REFERENCES saved_payment_methods (id);
ALTER TABLE payments ADD COLUMN autopay boolean NOT NULL DEFAULT false;
ALTER TABLE payments ADD CONSTRAINT payments_emi_only_for_emi CHECK (emi_tenure_months IS NULL OR method = 'EMI');
-- a provider payment can be recorded once, whether it arrives via the checkout callback or a webhook
CREATE UNIQUE INDEX ux_payments_provider_reference ON payments (provider, gateway_reference)
    WHERE provider IN ('RAZORPAY', 'SIMULATED') AND gateway_reference IS NOT NULL;

-- ---------------------------------------------------------------- hosted checkout
CREATE TABLE payment_intents (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id        bigint        NOT NULL REFERENCES invoices (id),
    member_id         bigint        NOT NULL REFERENCES members (id),
    provider          varchar(20)   NOT NULL CHECK (provider IN ('SIMULATED', 'RAZORPAY')),
    provider_order_id varchar(100)  NOT NULL UNIQUE,
    provider_customer_id varchar(100),
    amount            numeric(12, 2) NOT NULL CHECK (amount > 0),
    currency          varchar(3)    NOT NULL,
    method            varchar(20)   NOT NULL CHECK (method IN ('CARD', 'UPI', 'NET_BANKING', 'WALLET', 'EMI')),
    emi_tenure_months integer CHECK (emi_tenure_months IS NULL OR emi_tenure_months IN (3, 6, 9, 12)),
    save_method       boolean       NOT NULL DEFAULT false,
    setup_autopay     boolean       NOT NULL DEFAULT false,
    status            varchar(20)   NOT NULL DEFAULT 'CREATED'
        CHECK (status IN ('CREATED', 'SUCCEEDED', 'FAILED', 'EXPIRED', 'CANCELLED')),
    payment_id        bigint REFERENCES payments (id),
    failure_reason    varchar(300),
    idempotency_key   varchar(100)  NOT NULL UNIQUE,
    expires_at        timestamptz   NOT NULL,
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),
    created_by        bigint,
    updated_by        bigint,
    version           bigint        NOT NULL DEFAULT 0,
    CHECK (NOT setup_autopay OR (save_method AND method IN ('CARD', 'UPI')))
);
ALTER TABLE payments ADD COLUMN intent_id bigint REFERENCES payment_intents (id);
CREATE INDEX ix_payment_intents_invoice ON payment_intents (invoice_id, status);

CREATE TABLE webhook_events (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider        varchar(20)  NOT NULL,
    event_id        varchar(100) NOT NULL,
    event_type      varchar(60)  NOT NULL,
    payload         jsonb        NOT NULL,
    status          varchar(20)  NOT NULL CHECK (status IN ('PROCESSED', 'IGNORED', 'FAILED')),
    error           varchar(500),
    received_at     timestamptz  NOT NULL DEFAULT now(),
    UNIQUE (provider, event_id)
);

-- ---------------------------------------------------------------- refunds: where the money goes
ALTER TABLE refunds ADD COLUMN destination varchar(20) NOT NULL DEFAULT 'ORIGINAL_METHOD'
    CHECK (destination IN ('ORIGINAL_METHOD', 'STORE_CREDIT'));

-- ---------------------------------------------------------------- store credit (append-only ledger)
CREATE TABLE member_credit_ledger (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id     bigint        NOT NULL REFERENCES members (id),
    entry_type    varchar(20)   NOT NULL CHECK (entry_type IN ('ISSUED', 'REFUND', 'PAYMENT', 'ADJUSTMENT')),
    amount        numeric(12, 2) NOT NULL CHECK (amount <> 0),        -- + credit, - debit
    balance_after numeric(12, 2) NOT NULL CHECK (balance_after >= 0), -- can never go negative
    reason        varchar(300)  NOT NULL,
    payment_id    bigint REFERENCES payments (id),
    refund_id     bigint REFERENCES refunds (id),
    created_by    bigint,
    created_at    timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX ix_credit_ledger_member ON member_credit_ledger (member_id, id DESC);

-- ---------------------------------------------------------------- recurring billing (autopay)
ALTER TABLE subscriptions ADD COLUMN auto_renew boolean NOT NULL DEFAULT false;
ALTER TABLE subscriptions ADD COLUMN autopay_method_id bigint REFERENCES saved_payment_methods (id);
ALTER TABLE subscriptions ADD CONSTRAINT subscriptions_autopay_needs_method
    CHECK (NOT auto_renew OR autopay_method_id IS NOT NULL);
CREATE INDEX ix_subscriptions_autopay ON subscriptions (end_date) WHERE auto_renew;

CREATE TABLE autopay_attempts (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    subscription_id         bigint      NOT NULL REFERENCES subscriptions (id),   -- term being renewed
    renewal_subscription_id bigint      NOT NULL REFERENCES subscriptions (id),
    invoice_id              bigint      NOT NULL REFERENCES invoices (id),
    payment_method_id       bigint      NOT NULL REFERENCES saved_payment_methods (id),
    attempt_no              integer     NOT NULL CHECK (attempt_no BETWEEN 1 AND 10),
    scheduled_at            timestamptz NOT NULL,
    executed_at             timestamptz,
    status                  varchar(20) NOT NULL
        CHECK (status IN ('SCHEDULED', 'PROCESSING', 'SUCCEEDED', 'FAILED', 'SKIPPED', 'CANCELLED')),
    provider_order_id       varchar(100),              -- async debits are finalised by webhook via this id
    payment_id              bigint REFERENCES payments (id),
    failure_reason          varchar(300),
    pre_debit_notified_at   timestamptz,
    created_at              timestamptz NOT NULL DEFAULT now(),
    UNIQUE (invoice_id, attempt_no)
);
CREATE INDEX ix_autopay_attempts_due ON autopay_attempts (scheduled_at) WHERE status = 'SCHEDULED';
CREATE INDEX ix_autopay_attempts_subscription ON autopay_attempts (subscription_id);
CREATE INDEX ix_autopay_attempts_order ON autopay_attempts (provider_order_id) WHERE provider_order_id IS NOT NULL;
