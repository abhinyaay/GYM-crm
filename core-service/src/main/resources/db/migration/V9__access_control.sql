-- Access control: gate devices (turnstiles / doors / kiosks), member credentials (RFID card, rotating QR pass,
-- device-side biometric template references), DPDP biometric consent, device commands, the append-only access
-- event log and alarms.
--
-- Privacy: biometric matching happens ON THE DEVICE (ZKTeco / eSSL / Suprema style). No fingerprint or face
-- image or template is ever sent to or stored by GymOps; we keep only the device's opaque template reference.

-- Gate check-ins are recorded in the shared attendance table.
ALTER TABLE attendance DROP CONSTRAINT IF EXISTS attendance_check_in_method_check;
ALTER TABLE attendance ADD CONSTRAINT attendance_check_in_method_check
    CHECK (check_in_method IN ('FRONT_DESK', 'QR_CODE', 'MOBILE_APP', 'GATE'));

CREATE TABLE access_devices (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_uid        varchar(40)  NOT NULL,            -- public identifier sent in X-Device-Id (not guessable)
    branch_id         bigint       NOT NULL REFERENCES gym_branches (id),
    name              varchar(80)  NOT NULL,
    device_type       varchar(20)  NOT NULL CHECK (device_type IN ('TURNSTILE', 'DOOR', 'KIOSK')),
    direction         varchar(10)  NOT NULL CHECK (direction IN ('ENTRY', 'EXIT', 'BOTH')),
    vendor            varchar(60),
    model             varchar(60),
    serial_number     varchar(80),
    firmware_version  varchar(40),
    status            varchar(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    -- The device secret is never stored: it is derived as HMAC(ACCESS_MASTER_KEY, device_uid | key_version).
    -- Rotating the secret increments key_version, which invalidates the old secret immediately.
    key_version       int          NOT NULL DEFAULT 1 CHECK (key_version >= 1),
    secret_issued_at  timestamptz  NOT NULL,
    last_heartbeat_at timestamptz,
    last_seen_ip      varchar(64),
    offline_since     timestamptz,                      -- set by the heartbeat monitor, cleared by the next heartbeat
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    created_by        bigint,
    updated_by        bigint,
    version           bigint       NOT NULL DEFAULT 0,
    CONSTRAINT ux_access_devices_uid UNIQUE (device_uid)
);
CREATE UNIQUE INDEX ux_access_devices_branch_name ON access_devices (branch_id, lower(name));
CREATE UNIQUE INDEX ux_access_devices_serial ON access_devices (lower(serial_number)) WHERE serial_number IS NOT NULL;
CREATE INDEX ix_access_devices_heartbeat ON access_devices (status, last_heartbeat_at);

-- DPDP Act 2023: explicit, recorded consent for biometric processing (purpose, text version, who captured it, when).
CREATE TABLE biometric_consents (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id            bigint       NOT NULL REFERENCES members (id),
    purpose              varchar(40)  NOT NULL DEFAULT 'GYM_ENTRY_VERIFICATION',
    consent_text_version varchar(20)  NOT NULL,
    consent_text_sha256  varchar(64)  NOT NULL,
    capture_method       varchar(20)  NOT NULL CHECK (capture_method IN ('STAFF_ASSISTED', 'SELF_SERVICE')),
    granted_at           timestamptz  NOT NULL,
    granted_by           bigint REFERENCES users (id),
    withdrawn_at         timestamptz,
    withdrawn_by         bigint REFERENCES users (id),
    withdrawal_reason    varchar(300),
    CHECK (withdrawn_at IS NULL OR withdrawn_at >= granted_at)
);
CREATE UNIQUE INDEX ux_biometric_consent_active ON biometric_consents (member_id, purpose) WHERE withdrawn_at IS NULL;
CREATE INDEX ix_biometric_consents_member ON biometric_consents (member_id, granted_at DESC);

CREATE TABLE access_credentials (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id           bigint       NOT NULL REFERENCES members (id),
    credential_type     varchar(20)  NOT NULL CHECK (credential_type IN ('FINGERPRINT', 'FACE', 'RFID_CARD', 'QR')),
    status              varchar(20)  NOT NULL CHECK (status IN ('PENDING', 'ACTIVE', 'SUSPENDED', 'REVOKED')),
    -- SHA-256 of the normalised identifier (card UID / device template reference). Lookup key; never the raw UID.
    credential_hash     varchar(64),
    -- Opaque device-side template id (biometrics only), needed to send delete-template commands. Not biometric data.
    template_ref        varchar(80),
    display_hint        varchar(40),
    label               varchar(60),
    consent_id          bigint REFERENCES biometric_consents (id),
    enrolled_device_id  bigint REFERENCES access_devices (id),
    activated_at        timestamptz,
    suspended_at        timestamptz,
    suspension_source   varchar(20) CHECK (suspension_source IN ('MANUAL', 'MEMBER_STATUS')),
    revoked_at          timestamptz,
    revoked_by          bigint REFERENCES users (id),
    revoke_reason       varchar(200),
    created_at          timestamptz  NOT NULL DEFAULT now(),
    updated_at          timestamptz  NOT NULL DEFAULT now(),
    created_by          bigint,
    updated_by          bigint,
    version             bigint       NOT NULL DEFAULT 0,
    CONSTRAINT ck_access_credential_biometric_consent
        CHECK (credential_type NOT IN ('FINGERPRINT', 'FACE') OR consent_id IS NOT NULL),
    CONSTRAINT ck_access_credential_hash_present
        CHECK (status IN ('PENDING', 'REVOKED') OR credential_type = 'QR' OR credential_hash IS NOT NULL),
    CONSTRAINT ck_access_credential_suspension
        CHECK ((status = 'SUSPENDED') = (suspension_source IS NOT NULL))
);
-- One live credential per card UID / template across ALL members (a card can't belong to two people).
CREATE UNIQUE INDEX ux_access_credential_live_hash ON access_credentials (credential_type, credential_hash)
    WHERE status IN ('PENDING', 'ACTIVE', 'SUSPENDED') AND credential_hash IS NOT NULL;
-- At most one (non-revoked) rotating QR pass per member.
CREATE UNIQUE INDEX ux_access_credential_one_qr ON access_credentials (member_id)
    WHERE credential_type = 'QR' AND status <> 'REVOKED';
CREATE INDEX ix_access_credentials_member ON access_credentials (member_id, status);
CREATE INDEX ix_access_credentials_hash ON access_credentials (credential_hash) WHERE credential_hash IS NOT NULL;

-- Commands the server queues for a device (enrol / delete a template on the device), polled by the device.
CREATE TABLE access_device_commands (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id       bigint       NOT NULL REFERENCES access_devices (id),
    command_type    varchar(30)  NOT NULL CHECK (command_type IN ('ENROLL_TEMPLATE', 'DELETE_TEMPLATE')),
    credential_id   bigint REFERENCES access_credentials (id),
    credential_type varchar(20)  NOT NULL,
    template_ref    varchar(80),
    member_ref      varchar(40),
    status          varchar(20)  NOT NULL CHECK (status IN ('PENDING', 'DELIVERED', 'SUCCEEDED', 'FAILED', 'CANCELLED')),
    delivery_count  int          NOT NULL DEFAULT 0,
    created_at      timestamptz  NOT NULL,
    delivered_at    timestamptz,
    completed_at    timestamptz,
    result_message  varchar(300),
    version         bigint       NOT NULL DEFAULT 0
);
CREATE INDEX ix_access_commands_open ON access_device_commands (device_id, id) WHERE status IN ('PENDING', 'DELIVERED');
CREATE INDEX ix_access_commands_credential ON access_device_commands (credential_id);

-- Append-only log of every scan (granted or denied), including offline events reconciled later.
CREATE TABLE access_events (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id               bigint       NOT NULL REFERENCES access_devices (id),
    branch_id               bigint       NOT NULL REFERENCES gym_branches (id),
    device_event_id         varchar(80)  NOT NULL,
    member_id               bigint REFERENCES members (id),
    credential_id           bigint REFERENCES access_credentials (id),
    credential_type         varchar(20)  NOT NULL CHECK (credential_type IN ('FINGERPRINT', 'FACE', 'RFID_CARD', 'QR')),
    credential_hint         varchar(40),
    direction               varchar(10)  NOT NULL CHECK (direction IN ('ENTRY', 'EXIT')),
    decision                varchar(10)  NOT NULL CHECK (decision IN ('GRANTED', 'DENIED')),
    reason_code             varchar(40),
    message                 varchar(300),
    attendance_id           bigint REFERENCES attendance (id),
    offline                 boolean      NOT NULL DEFAULT false,
    anti_passback_violation boolean      NOT NULL DEFAULT false,
    occurred_at             timestamptz  NOT NULL,
    received_at             timestamptz  NOT NULL,
    CONSTRAINT ux_access_events_device_event UNIQUE (device_id, device_event_id)
);
CREATE INDEX ix_access_events_branch_time ON access_events (branch_id, occurred_at DESC);
CREATE INDEX ix_access_events_member_time ON access_events (member_id, occurred_at DESC) WHERE member_id IS NOT NULL;
CREATE INDEX ix_access_events_device_time ON access_events (device_id, occurred_at DESC);

CREATE FUNCTION access_events_append_only() RETURNS trigger AS $$
BEGIN
    RAISE EXCEPTION 'access_events is append-only (% rejected)', TG_OP;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_access_events_append_only
    BEFORE UPDATE OR DELETE ON access_events
    FOR EACH ROW EXECUTE FUNCTION access_events_append_only();

CREATE TABLE access_alarms (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id        bigint       NOT NULL REFERENCES access_devices (id),
    branch_id        bigint       NOT NULL REFERENCES gym_branches (id),
    device_event_id  varchar(80)  NOT NULL,
    alarm_type       varchar(30)  NOT NULL
        CHECK (alarm_type IN ('DOOR_FORCED', 'DOOR_HELD_OPEN', 'TAILGATING', 'TAMPER', 'DEVICE_OFFLINE')),
    details          varchar(300),
    occurred_at      timestamptz  NOT NULL,
    received_at      timestamptz  NOT NULL,
    acknowledged_at  timestamptz,
    acknowledged_by  bigint REFERENCES users (id),
    version          bigint       NOT NULL DEFAULT 0,
    CONSTRAINT ux_access_alarms_device_event UNIQUE (device_id, device_event_id)
);
CREATE INDEX ix_access_alarms_branch_open ON access_alarms (branch_id, occurred_at DESC) WHERE acknowledged_at IS NULL;

-- Single-use guard for device request nonces and QR pass windows (INSERT ... ON CONFLICT DO NOTHING).
CREATE TABLE access_replay_guard (
    scope      varchar(60)  NOT NULL,
    token      varchar(128) NOT NULL,
    expires_at timestamptz  NOT NULL,
    PRIMARY KEY (scope, token)
);
CREATE INDEX ix_access_replay_guard_expiry ON access_replay_guard (expires_at);

-- Analytics may read the event log and device list, never credentials or consent records.
DO $$
BEGIN
    IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gym_analytics_ro') THEN
        EXECUTE 'GRANT SELECT ON access_devices, access_events, access_alarms TO gym_analytics_ro';
        EXECUTE 'REVOKE SELECT ON access_credentials, biometric_consents, access_device_commands, access_replay_guard'
             || ' FROM gym_analytics_ro';
    END IF;
END
$$;
