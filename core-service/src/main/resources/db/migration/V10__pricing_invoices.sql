ALTER TABLE invoices ADD COLUMN supplier_state_code varchar(2);
ALTER TABLE invoices ADD COLUMN place_of_supply_code varchar(2);
ALTER TABLE invoices ADD COLUMN sac_code varchar(8);

-- ------------------------------------------------------------------ credit notes (refunds)
CREATE SEQUENCE credit_note_number_seq START 1;
ALTER TABLE refunds ADD COLUMN credit_note_number varchar(30);
WITH numbered AS (
    SELECT id, processed_at, row_number() OVER (ORDER BY processed_at, id) AS n FROM refunds
)
UPDATE refunds r
SET credit_note_number = 'CN-' || to_char(numbered.processed_at AT TIME ZONE 'Asia/Kolkata', 'YYYY')
                         || '-' || lpad(numbered.n::text, 6, '0')
FROM numbered WHERE numbered.id = r.id;
SELECT setval('credit_note_number_seq', GREATEST((SELECT count(*) FROM refunds), 1),
              (SELECT count(*) FROM refunds) > 0);
CREATE UNIQUE INDEX ux_refunds_credit_note_number ON refunds (credit_note_number);

