-- ------------------------------------------------------------------ GST registration
ALTER TABLE gym_branches ADD COLUMN gstin varchar(15);
ALTER TABLE gym_branches ADD COLUMN gst_state_code varchar(2);
ALTER TABLE gym_branches ADD CONSTRAINT gym_branches_gstin_format
    CHECK (gstin IS NULL OR gstin ~ '^[0-9]{2}[A-Z]{5}[0-9]{4}[A-Z][1-9A-Z]Z[0-9A-Z]$');
