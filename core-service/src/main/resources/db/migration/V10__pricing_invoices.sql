-- =====================================================================================
-- Pricing management & GST billing documents
--   * scheduled plan price changes with full history (who / when / old / new / effective)
--   * per-subscription price protection ("grandfathering") and negotiated prices
--   * advance notice of renewal price rises to autopay members
--   * GST registration of branches, tax snapshot on invoices, credit-note numbering
-- =====================================================================================

-- ------------------------------------------------------------------ plan price history
CREATE TABLE plan_price_changes (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id                bigint         NOT NULL REFERENCES membership_plans (id),
    old_price              numeric(12, 2) NOT NULL CHECK (old_price >= 0),
    new_price              numeric(12, 2) NOT NULL CHECK (new_price >= 0),
    old_joining_fee        numeric(12, 2) NOT NULL CHECK (old_joining_fee >= 0),
    new_joining_fee        numeric(12, 2) NOT NULL CHECK (new_joining_fee >= 0),
    effective_date         date           NOT NULL,
    existing_member_policy varchar(30)    NOT NULL
        CHECK (existing_member_policy IN ('NEW_PRICE_AT_RENEWAL', 'PROTECT_EXISTING')),
    protected_until        date,
    reason                 varchar(500)   NOT NULL,
    source                 varchar(20)    NOT NULL CHECK (source IN ('SCHEDULED', 'DIRECT_EDIT')),
    status                 varchar(20)    NOT NULL CHECK (status IN ('SCHEDULED', 'APPLIED', 'CANCELLED')),
    applied_at             timestamptz,
    protected_count        int,
    notified_count         int            NOT NULL DEFAULT 0,
    cancelled_at           timestamptz,
    cancelled_by           bigint REFERENCES users (id),
    cancel_reason          varchar(500),
    created_at             timestamptz    NOT NULL DEFAULT now(),
    updated_at             timestamptz    NOT NULL DEFAULT now(),
    created_by             bigint,
    updated_by             bigint,
    version                bigint         NOT NULL DEFAULT 0,
    CONSTRAINT plan_price_changes_protection CHECK (
        (existing_member_policy = 'PROTECT_EXISTING') = (protected_until IS NOT NULL)),
    CONSTRAINT plan_price_changes_protection_after_effective CHECK (
        protected_until IS NULL OR protected_until >= effective_date),
    CONSTRAINT plan_price_changes_applied CHECK ((status = 'APPLIED') = (applied_at IS NOT NULL)),
    CONSTRAINT plan_price_changes_cancelled CHECK ((status = 'CANCELLED') = (cancelled_at IS NOT NULL))
);
-- at most one pending change per plan: a second one must wait until the first applies or is cancelled
CREATE UNIQUE INDEX ux_plan_price_changes_one_scheduled ON plan_price_changes (plan_id) WHERE status = 'SCHEDULED';
CREATE INDEX ix_plan_price_changes_plan ON plan_price_changes (plan_id, created_at DESC);
CREATE INDEX ix_plan_price_changes_due ON plan_price_changes (effective_date) WHERE status = 'SCHEDULED';

-- ------------------------------------------------------------------ per-subscription pricing
ALTER TABLE subscriptions ADD COLUMN list_price numeric(12, 2) CHECK (list_price IS NULL OR list_price >= 0);
ALTER TABLE subscriptions ADD COLUMN price_basis varchar(20) NOT NULL DEFAULT 'LIST'
    CHECK (price_basis IN ('LIST', 'NEGOTIATED', 'PRICE_PROTECTED', 'NOTICE_HELD'));
ALTER TABLE subscriptions ADD COLUMN price_override_reason varchar(300);
ALTER TABLE subscriptions ADD COLUMN keep_price_on_renewal boolean NOT NULL DEFAULT false;
ALTER TABLE subscriptions ADD COLUMN locked_price numeric(12, 2) CHECK (locked_price IS NULL OR locked_price >= 0);
ALTER TABLE subscriptions ADD COLUMN price_protected_until date;
ALTER TABLE subscriptions ADD COLUMN price_change_id bigint REFERENCES plan_price_changes (id);
ALTER TABLE subscriptions ADD CONSTRAINT subscriptions_price_lock_complete
    CHECK ((locked_price IS NULL) = (price_protected_until IS NULL));
ALTER TABLE subscriptions ADD CONSTRAINT subscriptions_negotiated_needs_reason
    CHECK (price_basis <> 'NEGOTIATED' OR price_override_reason IS NOT NULL);
ALTER TABLE subscriptions ADD CONSTRAINT subscriptions_keep_price_needs_negotiation
    CHECK (NOT keep_price_on_renewal OR price_override_reason IS NOT NULL);

-- Advance notice of a renewal price rise, per member and plan. An autopay renewal is debited at a
-- higher price only if a notice for at least that price was sent app.pricing.price-change-notice-days
-- before the debit; otherwise that renewal keeps the member's current price.
CREATE TABLE price_change_notices (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id       bigint         NOT NULL REFERENCES members (id),
    plan_id         bigint         NOT NULL REFERENCES membership_plans (id),
    subscription_id bigint         NOT NULL REFERENCES subscriptions (id),
    price_change_id bigint REFERENCES plan_price_changes (id),
    current_price   numeric(12, 2) NOT NULL CHECK (current_price >= 0),
    new_price       numeric(12, 2) NOT NULL CHECK (new_price >= 0),
    first_debit_on  date,
    notified_at     timestamptz    NOT NULL,
    CONSTRAINT ux_price_change_notices UNIQUE (member_id, plan_id, new_price)
);
CREATE INDEX ix_price_change_notices_change ON price_change_notices (price_change_id);

-- ------------------------------------------------------------------ invoice lines
