-- =====================================================================================
-- Group classes: class catalogue, scheduled sessions, bookings with waitlist.
-- Capacity is enforced under a row lock on the session; double booking by a partial unique index.
-- =====================================================================================

-- monthly class entitlement per plan: NULL = unlimited, 0 = no classes included
ALTER TABLE membership_plans ADD COLUMN class_credits_per_month int
    CHECK (class_credits_per_month IS NULL OR class_credits_per_month >= 0);

CREATE TABLE class_types (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                  varchar(80)   NOT NULL,
    description           varchar(1000),
    category              varchar(20)   NOT NULL
        CHECK (category IN ('YOGA', 'HIIT', 'CYCLING', 'STRENGTH', 'DANCE', 'PILATES', 'BOXING', 'MOBILITY', 'OTHER')),
    intensity             varchar(20)   NOT NULL CHECK (intensity IN ('LOW', 'MEDIUM', 'HIGH')),
    default_duration_min  int           NOT NULL CHECK (default_duration_min BETWEEN 15 AND 180),
    default_capacity      int           NOT NULL CHECK (default_capacity BETWEEN 1 AND 200),
    active                boolean       NOT NULL DEFAULT true,
    created_at            timestamptz   NOT NULL DEFAULT now(),
    updated_at            timestamptz   NOT NULL DEFAULT now(),
    created_by            bigint,
    updated_by            bigint,
    version               bigint        NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_class_types_name ON class_types (lower(name));

CREATE TABLE class_sessions (
    id                     bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_type_id          bigint       NOT NULL REFERENCES class_types (id),
    branch_id              bigint       NOT NULL REFERENCES gym_branches (id),
    instructor_id          bigint       NOT NULL REFERENCES trainers (id),
    room                   varchar(60),
    starts_at              timestamptz  NOT NULL,
    ends_at                timestamptz  NOT NULL,
    capacity               int          NOT NULL CHECK (capacity BETWEEN 1 AND 200),
    waitlist_capacity      int          NOT NULL DEFAULT 10 CHECK (waitlist_capacity BETWEEN 0 AND 100),
    booking_opens_hours    int          NOT NULL DEFAULT 168 CHECK (booking_opens_hours BETWEEN 1 AND 720),
    cancel_cutoff_minutes  int          NOT NULL DEFAULT 120 CHECK (cancel_cutoff_minutes BETWEEN 0 AND 1440),
    status                 varchar(20)  NOT NULL DEFAULT 'SCHEDULED' CHECK (status IN ('SCHEDULED', 'CANCELLED', 'COMPLETED')),
    series_id              uuid,                       -- sessions created together from a recurring schedule
    cancellation_reason    varchar(300),
    created_at             timestamptz  NOT NULL DEFAULT now(),
    updated_at             timestamptz  NOT NULL DEFAULT now(),
    created_by             bigint,
    updated_by             bigint,
    version                bigint       NOT NULL DEFAULT 0,
    CHECK (ends_at > starts_at),
    -- an instructor cannot teach two overlapping classes
    CONSTRAINT ex_class_sessions_instructor_no_overlap EXCLUDE USING gist (
        instructor_id WITH =, tstzrange(starts_at, ends_at) WITH &&
    ) WHERE (status = 'SCHEDULED')
);
CREATE INDEX ix_class_sessions_branch_start ON class_sessions (branch_id, starts_at);
CREATE INDEX ix_class_sessions_series ON class_sessions (series_id);

CREATE TABLE class_bookings (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     bigint       NOT NULL REFERENCES class_sessions (id),
    member_id      bigint       NOT NULL REFERENCES members (id),
    status         varchar(20)  NOT NULL
        CHECK (status IN ('BOOKED', 'WAITLISTED', 'CANCELLED', 'LATE_CANCELLED', 'ATTENDED', 'NO_SHOW')),
    booked_at      timestamptz  NOT NULL DEFAULT now(),
    promoted_at    timestamptz,                -- moved from waitlist to booked
    cancelled_at   timestamptz,
    attended_at    timestamptz,
    booked_by      bigint REFERENCES users (id),
    created_at     timestamptz  NOT NULL DEFAULT now(),
    updated_at     timestamptz  NOT NULL DEFAULT now(),
    version        bigint       NOT NULL DEFAULT 0
);
-- one live booking per member per session
CREATE UNIQUE INDEX ux_class_booking_live ON class_bookings (session_id, member_id) WHERE status IN ('BOOKED', 'WAITLISTED');
CREATE INDEX ix_class_bookings_session ON class_bookings (session_id, status, booked_at);
CREATE INDEX ix_class_bookings_member ON class_bookings (member_id, booked_at DESC);
