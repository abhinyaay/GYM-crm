-- =====================================================================================
-- Growth: member referral programme and retention (win-back) campaigns.
-- =====================================================================================

-- -------------------------------------------------------------------------------------
-- Referral codes: one stable, human-friendly code per member, generated lazily.
-- -------------------------------------------------------------------------------------
CREATE TABLE referral_codes (
    member_id  bigint      PRIMARY KEY REFERENCES members (id),
    code       varchar(16) NOT NULL CHECK (code ~ '^[A-Z0-9]{5,16}$'),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_referral_codes_code ON referral_codes (code);

-- -------------------------------------------------------------------------------------
-- Referrals: who referred whom. A referee is first known as a lead (website enquiry) or a
-- member (desk / self sign-up); the member is linked once they exist. One referral per
-- referee member and per lead (first referral wins).
--
--   PENDING   -> CONVERTED  first paid (non-trial) membership activated; rewards HELD
--   PENDING   -> REJECTED   fraud guard failed (self-referral, referee not new)
--   CONVERTED -> REVERSED   qualifying payment refunded / subscription cancelled during the hold
-- -------------------------------------------------------------------------------------
CREATE TABLE referrals (
    id                         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referrer_member_id         bigint       NOT NULL REFERENCES members (id),
    code                       varchar(16)  NOT NULL,
    referee_member_id          bigint REFERENCES members (id),
    referee_lead_id            bigint REFERENCES leads (id),
    referee_first_name         varchar(80)  NOT NULL,
    referee_last_name          varchar(80),
    referee_email              varchar(254),
    referee_phone              varchar(20),
    branch_id                  bigint       NOT NULL REFERENCES gym_branches (id),   -- referee's branch (staff scoping)
    channel                    varchar(20)  NOT NULL CHECK (channel IN ('LINK', 'DESK', 'SELF_SIGNUP')),
    status                     varchar(20)  NOT NULL DEFAULT 'PENDING'
        CHECK (status IN ('PENDING', 'CONVERTED', 'REVERSED', 'REJECTED')),
    rejection_reason           varchar(30)
        CHECK (rejection_reason IS NULL OR rejection_reason IN ('SELF_REFERRAL', 'NOT_NEW')),
    qualifying_subscription_id bigint REFERENCES subscriptions (id),
    qualifying_invoice_id      bigint REFERENCES invoices (id),
    converted_at               timestamptz,
    hold_until                 timestamptz,
    referrer_reward_skipped    varchar(30)
        CHECK (referrer_reward_skipped IS NULL OR referrer_reward_skipped IN ('MONTHLY_CAP', 'REFERRER_INACTIVE')),
    reversed_at                timestamptz,
    reversal_reason            varchar(300),
    created_at                 timestamptz  NOT NULL DEFAULT now(),
    updated_at                 timestamptz  NOT NULL DEFAULT now(),
    created_by                 bigint,
    updated_by                 bigint,
    version                    bigint       NOT NULL DEFAULT 0,
    CHECK (referee_member_id IS NOT NULL OR referee_lead_id IS NOT NULL),
    CONSTRAINT ck_referrals_not_self CHECK (referee_member_id IS NULL OR referee_member_id <> referrer_member_id),
    CHECK ((status = 'REJECTED') = (rejection_reason IS NOT NULL)),
    CHECK ((status IN ('CONVERTED', 'REVERSED')) = (converted_at IS NOT NULL)),
    CHECK ((status IN ('CONVERTED', 'REVERSED')) = (qualifying_subscription_id IS NOT NULL)),
    CHECK ((status = 'REVERSED') = (reversed_at IS NOT NULL))
);
CREATE UNIQUE INDEX ux_referrals_referee_member ON referrals (referee_member_id) WHERE referee_member_id IS NOT NULL;
CREATE UNIQUE INDEX ux_referrals_referee_lead ON referrals (referee_lead_id) WHERE referee_lead_id IS NOT NULL;
CREATE INDEX ix_referrals_referrer ON referrals (referrer_member_id, created_at DESC);
CREATE INDEX ix_referrals_branch_status ON referrals (branch_id, status, created_at DESC);
CREATE INDEX ix_referrals_pending_email ON referrals (lower(referee_email)) WHERE status = 'PENDING';
CREATE INDEX ix_referrals_pending_phone ON referrals (referee_phone) WHERE status = 'PENDING';

-- -------------------------------------------------------------------------------------
-- Rewards: at most one per referral and beneficiary (so one referrer reward per referee).
-- HELD until the hold period ends, then AVAILABLE (credit posted / code issued) or REVERSED.
-- -------------------------------------------------------------------------------------
CREATE TABLE referral_rewards (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    referral_id     bigint        NOT NULL REFERENCES referrals (id),
    member_id       bigint        NOT NULL REFERENCES members (id),
    beneficiary     varchar(10)   NOT NULL CHECK (beneficiary IN ('REFERRER', 'REFEREE')),
    reward_type     varchar(20)   NOT NULL CHECK (reward_type IN ('STORE_CREDIT', 'DISCOUNT_CODE')),
    amount          numeric(12, 2) NOT NULL CHECK (amount > 0),     -- credit amount or discount value
    discount_type   varchar(20) CHECK (discount_type IS NULL OR discount_type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    status          varchar(20)   NOT NULL DEFAULT 'HELD' CHECK (status IN ('HELD', 'AVAILABLE', 'REVERSED')),
    available_at    timestamptz   NOT NULL,
    released_at     timestamptz,
    reversed_at     timestamptz,
    credit_entry_id bigint REFERENCES member_credit_ledger (id),
    discount_id     bigint REFERENCES discounts (id),
    created_at      timestamptz   NOT NULL DEFAULT now(),
    updated_at      timestamptz   NOT NULL DEFAULT now(),
    created_by      bigint,
    updated_by      bigint,
    version         bigint        NOT NULL DEFAULT 0,
    CONSTRAINT ux_referral_rewards_one_per_beneficiary UNIQUE (referral_id, beneficiary),
    CHECK ((reward_type = 'DISCOUNT_CODE') = (discount_type IS NOT NULL)),
    CHECK (discount_type IS DISTINCT FROM 'PERCENTAGE' OR amount <= 100),
    CHECK ((status = 'AVAILABLE') = (released_at IS NOT NULL)),
    CHECK ((status = 'REVERSED') = (reversed_at IS NOT NULL)),
    CHECK (status <> 'AVAILABLE' OR credit_entry_id IS NOT NULL OR discount_id IS NOT NULL)
);
CREATE INDEX ix_referral_rewards_due ON referral_rewards (available_at) WHERE status = 'HELD';
CREATE INDEX ix_referral_rewards_member ON referral_rewards (member_id, created_at DESC);

-- -------------------------------------------------------------------------------------
-- Personal (single-member) discount codes: referral welcome codes and campaign offers.
-- The code itself is an ordinary single-use row in `discounts`; this table binds it to one
-- member and the trigger below rejects an invoice for anyone else, whatever code path
-- applies the discount.
-- -------------------------------------------------------------------------------------
CREATE TABLE personal_discount_codes (
    discount_id bigint      PRIMARY KEY REFERENCES discounts (id),
    member_id   bigint      NOT NULL REFERENCES members (id),
    purpose     varchar(20) NOT NULL CHECK (purpose IN ('REFERRAL_WELCOME', 'CAMPAIGN_OFFER')),
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_personal_discount_codes_member ON personal_discount_codes (member_id);

CREATE FUNCTION enforce_personal_discount_owner() RETURNS trigger
    LANGUAGE plpgsql AS
$$
BEGIN
    IF NEW.discount_id IS NOT NULL AND EXISTS (
            SELECT 1 FROM personal_discount_codes p
            WHERE p.discount_id = NEW.discount_id AND p.member_id <> NEW.member_id) THEN
        RAISE EXCEPTION 'personal discount code belongs to another member: violates check constraint "ck_personal_discount_owner"'
            USING ERRCODE = '23514', CONSTRAINT = 'ck_personal_discount_owner';
    END IF;
    RETURN NEW;
END
$$;

CREATE TRIGGER trg_invoices_personal_discount_owner
    BEFORE INSERT OR UPDATE OF discount_id, member_id ON invoices
    FOR EACH ROW EXECUTE FUNCTION enforce_personal_discount_owner();

-- -------------------------------------------------------------------------------------
-- Retention / win-back campaigns
-- -------------------------------------------------------------------------------------
CREATE TABLE campaigns (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                 varchar(120)  NOT NULL,
    description          varchar(500),
    branch_id            bigint REFERENCES gym_branches (id),      -- NULL = every branch (org-wide staff only)
    segment              varchar(30)   NOT NULL
        CHECK (segment IN ('CHURN_RISK', 'EXPIRING_NO_AUTOPAY', 'LAPSED', 'NO_RECENT_VISIT', 'TRIAL_NOT_CONVERTED')),
    churn_band           varchar(10) CHECK (churn_band IS NULL OR churn_band IN ('HIGH', 'MEDIUM')),
    segment_days         int CHECK (segment_days IS NULL OR segment_days BETWEEN 1 AND 365),
    segment_days_max     int CHECK (segment_days_max IS NULL OR segment_days_max BETWEEN 1 AND 365),
    title_template       varchar(200)  NOT NULL,
    message_template     varchar(1500) NOT NULL,
    offer_enabled        boolean       NOT NULL DEFAULT false,
    offer_discount_type  varchar(20) CHECK (offer_discount_type IS NULL OR offer_discount_type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    offer_value          numeric(12, 2) CHECK (offer_value IS NULL OR offer_value > 0),
    offer_valid_days     int CHECK (offer_valid_days IS NULL OR offer_valid_days BETWEEN 1 AND 365),
    schedule             varchar(10)   NOT NULL DEFAULT 'NONE' CHECK (schedule IN ('NONE', 'DAILY', 'WEEKLY')),
    schedule_day_of_week int CHECK (schedule_day_of_week IS NULL OR schedule_day_of_week BETWEEN 1 AND 7),
    status               varchar(20)   NOT NULL DEFAULT 'DRAFT' CHECK (status IN ('DRAFT', 'ACTIVE', 'PAUSED', 'ARCHIVED')),
    cooldown_days        int           NOT NULL CHECK (cooldown_days BETWEEN 0 AND 365),
    attribution_days     int           NOT NULL CHECK (attribution_days BETWEEN 1 AND 180),
    next_run_at          timestamptz,
    last_run_at          timestamptz,
    run_lock_until       timestamptz,                               -- simple per-campaign run mutex
    created_at           timestamptz   NOT NULL DEFAULT now(),
    updated_at           timestamptz   NOT NULL DEFAULT now(),
    created_by           bigint,
    updated_by           bigint,
    version              bigint        NOT NULL DEFAULT 0,
    CHECK ((segment = 'CHURN_RISK') = (churn_band IS NOT NULL)),
    CHECK (segment = 'CHURN_RISK' OR segment_days IS NOT NULL),
    CHECK ((segment = 'LAPSED') = (segment_days_max IS NOT NULL)),
    CHECK (segment_days_max IS NULL OR segment_days_max >= segment_days),
    CHECK (NOT offer_enabled OR (offer_discount_type IS NOT NULL AND offer_value IS NOT NULL AND offer_valid_days IS NOT NULL)),
    CHECK (offer_discount_type IS DISTINCT FROM 'PERCENTAGE' OR offer_value <= 100),
    CHECK ((schedule = 'WEEKLY') = (schedule_day_of_week IS NOT NULL)),
    CHECK (status <> 'ACTIVE' OR schedule <> 'NONE')
);
CREATE INDEX ix_campaigns_due ON campaigns (next_run_at) WHERE status = 'ACTIVE';
CREATE INDEX ix_campaigns_branch ON campaigns (branch_id, status);

CREATE TABLE campaign_runs (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id      bigint       NOT NULL REFERENCES campaigns (id),
    trigger_type     varchar(10)  NOT NULL CHECK (trigger_type IN ('MANUAL', 'SCHEDULED')),
    status           varchar(20)  NOT NULL CHECK (status IN ('RUNNING', 'COMPLETED', 'FAILED')),
    audience_size    int          NOT NULL DEFAULT 0,
    sent             int          NOT NULL DEFAULT 0,
    skipped          int          NOT NULL DEFAULT 0,      -- in cooldown or no longer eligible
    failed           int          NOT NULL DEFAULT 0,
    error            varchar(500),
    triggered_by     bigint,
    started_at       timestamptz  NOT NULL,
    finished_at      timestamptz
);
CREATE INDEX ix_campaign_runs_campaign ON campaign_runs (campaign_id, started_at DESC);

CREATE TABLE campaign_recipients (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    campaign_id           bigint       NOT NULL REFERENCES campaigns (id),
    run_id                bigint       NOT NULL REFERENCES campaign_runs (id),
    member_id             bigint       NOT NULL REFERENCES members (id),
    branch_id             bigint       NOT NULL REFERENCES gym_branches (id),
    sent_at               timestamptz  NOT NULL,
    discount_id           bigint REFERENCES discounts (id),
    offer_code            varchar(30),
    attribution_ends_at   timestamptz  NOT NULL,
    converted_at          timestamptz,
    conversion_invoice_id bigint REFERENCES invoices (id),
    conversion_amount     numeric(12, 2),
    offer_redeemed        boolean      NOT NULL DEFAULT false,
    CONSTRAINT ux_campaign_recipients_run_member UNIQUE (run_id, member_id),
    CHECK ((converted_at IS NULL) = (conversion_invoice_id IS NULL)),
    CHECK ((discount_id IS NULL) = (offer_code IS NULL)),
    CHECK (NOT offer_redeemed OR converted_at IS NOT NULL)
);
-- last-touch attribution: an invoice converts at most one campaign message
CREATE UNIQUE INDEX ux_campaign_recipients_conversion ON campaign_recipients (conversion_invoice_id)
    WHERE conversion_invoice_id IS NOT NULL;
CREATE INDEX ix_campaign_recipients_campaign ON campaign_recipients (campaign_id, sent_at DESC);
CREATE INDEX ix_campaign_recipients_member ON campaign_recipients (member_id, sent_at DESC);

