-- =====================================================================================
-- E-mail & SMS channels: provider receipts on the outbox, a SKIPPED status (opted out /
-- no usable phone), member notification preferences and an index for the messaging centre.
-- =====================================================================================

-- SKIPPED: deliberately not delivered (never retried). The V1 status CHECK is column-level with a
-- generated name, so it is looked up rather than assumed.
DO $$
DECLARE
    c text;
BEGIN
    FOR c IN
        SELECT conname FROM pg_constraint
        WHERE conrelid = 'notifications'::regclass AND contype = 'c'
          AND pg_get_constraintdef(oid) LIKE '%status%' AND pg_get_constraintdef(oid) LIKE '%FAILED%'
    LOOP
        EXECUTE format('ALTER TABLE notifications DROP CONSTRAINT %I', c);
    END LOOP;
END $$;

ALTER TABLE notifications
    ADD CONSTRAINT ck_notifications_status CHECK (status IN ('PENDING', 'SENT', 'FAILED', 'SKIPPED')),
    ADD COLUMN provider             varchar(20),           -- smtp | twilio | msg91 | log
    ADD COLUMN provider_message_id  varchar(255),          -- SMTP Message-ID / Twilio SID / MSG91 request id
    ADD COLUMN segments             integer CHECK (segments IS NULL OR segments >= 0),   -- billable SMS segments
    ADD COLUMN requested_by_user_id bigint REFERENCES users (id);   -- staff who triggered a test send / resend

-- messaging centre: newest first, per member
CREATE INDEX ix_notifications_created ON notifications (created_at DESC);
CREATE INDEX ix_notifications_member ON notifications (member_id, created_at DESC) WHERE member_id IS NOT NULL;

-- -------------------------------------------------------------------------------------
-- Member notification preferences: explicit choices per category x channel. No row means
-- the category default (MARKETING: e-mail on, SMS off). Locked channels (BILLING / ACCOUNT
-- e-mail: receipts, pre-debit notices, security notices) are enforced in code.
-- -------------------------------------------------------------------------------------
CREATE TABLE member_notification_preferences (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id  bigint      NOT NULL REFERENCES members (id) ON DELETE CASCADE,
    category   varchar(20) NOT NULL,
    channel    varchar(10) NOT NULL CHECK (channel IN ('EMAIL', 'SMS')),
    enabled    boolean     NOT NULL,
    source     varchar(20) NOT NULL CHECK (source IN ('MEMBER', 'STAFF', 'UNSUBSCRIBE_LINK')),
    updated_by bigint REFERENCES users (id),
    updated_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT ux_member_notification_pref UNIQUE (member_id, category, channel)
);
