CREATE INDEX ix_members_branch_status ON members (home_branch_id, status) WHERE deleted_at IS NULL;
CREATE INDEX ix_members_last_name ON members (lower(last_name));
CREATE INDEX ix_members_registered_at ON members (registered_at);

CREATE TABLE emergency_contacts (
