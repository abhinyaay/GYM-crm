-- -------------------------------------------------------------------------------------
-- Membership plans & discounts
-- -------------------------------------------------------------------------------------
CREATE TABLE membership_plans (
    id                   bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 varchar(30)   NOT NULL UNIQUE,
    name                 varchar(120)  NOT NULL,
    description          varchar(1000),
    billing_period       varchar(20)   NOT NULL
        CHECK (billing_period IN ('MONTHLY', 'QUARTERLY', 'HALF_YEARLY', 'ANNUAL', 'CUSTOM')),
    duration_months      int,
    duration_days        int,
    price                numeric(12, 2) NOT NULL CHECK (price >= 0),
    currency             varchar(3)       NOT NULL DEFAULT 'INR',
    joining_fee          numeric(12, 2) NOT NULL DEFAULT 0 CHECK (joining_fee >= 0),
    all_branch_access    boolean       NOT NULL DEFAULT false,
    access_start_time    time,
    access_end_time      time,
    max_visits_per_month int CHECK (max_visits_per_month IS NULL OR max_visits_per_month > 0),
    freeze_allowed       boolean       NOT NULL DEFAULT false,
    min_freeze_days      int           NOT NULL DEFAULT 0 CHECK (min_freeze_days >= 0),
    max_freeze_days      int           NOT NULL DEFAULT 0 CHECK (max_freeze_days >= 0),
    max_freeze_count     int           NOT NULL DEFAULT 0 CHECK (max_freeze_count >= 0),
    cancellation_policy  varchar(30)   NOT NULL
        CHECK (cancellation_policy IN ('NON_REFUNDABLE', 'PRORATED', 'COOLING_OFF_FULL_REFUND')),
    cooling_off_days     int           NOT NULL DEFAULT 0 CHECK (cooling_off_days >= 0),
    cancellation_fee     numeric(12, 2) NOT NULL DEFAULT 0 CHECK (cancellation_fee >= 0),
    grace_period_days    int           NOT NULL DEFAULT 0 CHECK (grace_period_days >= 0),
    status               varchar(20)   NOT NULL DEFAULT 'DRAFT'
        CHECK (status IN ('DRAFT', 'ACTIVE', 'ARCHIVED')),
    created_at           timestamptz   NOT NULL DEFAULT now(),
    updated_at           timestamptz   NOT NULL DEFAULT now(),
    created_by           bigint,
    updated_by           bigint,
    version              bigint        NOT NULL DEFAULT 0,
    CHECK ((billing_period = 'CUSTOM' AND duration_days > 0)
        OR (billing_period <> 'CUSTOM' AND duration_months > 0)),
    CHECK ((access_start_time IS NULL) = (access_end_time IS NULL)),
    CHECK (NOT freeze_allowed OR max_freeze_days >= min_freeze_days)
);

CREATE TABLE plan_benefits (
    plan_id  bigint       NOT NULL REFERENCES membership_plans (id) ON DELETE CASCADE,
    position int          NOT NULL,
    benefit  varchar(200) NOT NULL,
    PRIMARY KEY (plan_id, position)
);

CREATE TABLE discounts (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            varchar(30)   NOT NULL,
    description     varchar(300),
    discount_type   varchar(20)   NOT NULL CHECK (discount_type IN ('PERCENTAGE', 'FIXED_AMOUNT')),
    value           numeric(12, 2) NOT NULL CHECK (value > 0),
    valid_from      date          NOT NULL,
    valid_until     date,
    max_redemptions int CHECK (max_redemptions IS NULL OR max_redemptions > 0),
    times_redeemed  int           NOT NULL DEFAULT 0,
    active          boolean       NOT NULL DEFAULT true,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    updated_at      timestamptz   NOT NULL DEFAULT now(),
    created_by      bigint,
    updated_by      bigint,
    version         bigint        NOT NULL DEFAULT 0,
    CHECK (discount_type <> 'PERCENTAGE' OR value <= 100),
    CHECK (valid_until IS NULL OR valid_until >= valid_from),
    CHECK (max_redemptions IS NULL OR times_redeemed <= max_redemptions)
);
CREATE UNIQUE INDEX ux_discounts_code ON discounts (upper(code));

-- -------------------------------------------------------------------------------------
-- Subscriptions
-- -------------------------------------------------------------------------------------
CREATE TABLE subscriptions (
    id                       bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id                bigint        NOT NULL REFERENCES members (id),
    plan_id                  bigint        NOT NULL REFERENCES membership_plans (id),
    branch_id                bigint        NOT NULL REFERENCES gym_branches (id),
    previous_subscription_id bigint REFERENCES subscriptions (id),
    status                   varchar(20)   NOT NULL
        CHECK (status IN ('PENDING_PAYMENT', 'SCHEDULED', 'ACTIVE', 'FROZEN', 'GRACE',
                          'EXPIRED', 'CANCELLED', 'SUPERSEDED')),
    change_type              varchar(20)   NOT NULL
        CHECK (change_type IN ('NEW', 'RENEWAL', 'UPGRADE', 'DOWNGRADE')),
    start_date               date          NOT NULL,
    end_date                 date          NOT NULL,
    price                    numeric(12, 2) NOT NULL CHECK (price >= 0),   -- plan price snapshot
    freeze_days_used         int           NOT NULL DEFAULT 0,
    freeze_count             int           NOT NULL DEFAULT 0,
    frozen_from              date,
    frozen_until             date,
    activated_at             timestamptz,
    cancelled_at             timestamptz,
    cancellation_reason      varchar(500),
    created_at               timestamptz   NOT NULL DEFAULT now(),
    updated_at               timestamptz   NOT NULL DEFAULT now(),
    created_by               bigint,
    updated_by               bigint,
    version                  bigint        NOT NULL DEFAULT 0,
    CHECK (end_date >= start_date),
    CHECK ((frozen_from IS NULL) = (frozen_until IS NULL)),
    -- A member can never hold two committed (paid / access-granting) subscriptions whose
    -- date ranges overlap. Enforced by the database so it holds under any concurrency.
    CONSTRAINT ex_subscriptions_no_overlap EXCLUDE USING gist (
        member_id WITH =,
        daterange(start_date, end_date, '[]') WITH &&
    ) WHERE (status IN ('SCHEDULED', 'ACTIVE', 'FROZEN', 'GRACE'))
);
-- at most one unpaid subscription per member at a time
CREATE UNIQUE INDEX ux_subscriptions_one_pending ON subscriptions (member_id) WHERE status = 'PENDING_PAYMENT';
CREATE INDEX ix_subscriptions_member ON subscriptions (member_id, start_date DESC);
CREATE INDEX ix_subscriptions_status_end ON subscriptions (status, end_date);
CREATE INDEX ix_subscriptions_plan ON subscriptions (plan_id);
CREATE INDEX ix_subscriptions_previous ON subscriptions (previous_subscription_id);

-- -------------------------------------------------------------------------------------
-- Billing: invoices, payments, refunds
-- -------------------------------------------------------------------------------------
CREATE TABLE invoices (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_number  varchar(30)   NOT NULL UNIQUE,
    member_id       bigint        NOT NULL REFERENCES members (id),
    subscription_id bigint REFERENCES subscriptions (id),
    branch_id       bigint        NOT NULL REFERENCES gym_branches (id),
    status          varchar(20)   NOT NULL
        CHECK (status IN ('ISSUED', 'PAID', 'VOID', 'PARTIALLY_REFUNDED', 'REFUNDED')),
    currency        varchar(3)       NOT NULL,
    subtotal        numeric(12, 2) NOT NULL CHECK (subtotal >= 0),
    discount_id     bigint REFERENCES discounts (id),
    discount_amount numeric(12, 2) NOT NULL DEFAULT 0 CHECK (discount_amount >= 0),
    tax_rate        numeric(6, 4) NOT NULL CHECK (tax_rate >= 0),
    tax_amount      numeric(12, 2) NOT NULL CHECK (tax_amount >= 0),
    total_amount    numeric(12, 2) NOT NULL CHECK (total_amount >= 0),
    amount_paid     numeric(12, 2) NOT NULL DEFAULT 0 CHECK (amount_paid >= 0),
    amount_refunded numeric(12, 2) NOT NULL DEFAULT 0 CHECK (amount_refunded >= 0),
    due_date        date          NOT NULL,
    issued_at       timestamptz   NOT NULL DEFAULT now(),
    paid_at         timestamptz,
    voided_at       timestamptz,
    created_at      timestamptz   NOT NULL DEFAULT now(),
    updated_at      timestamptz   NOT NULL DEFAULT now(),
    created_by      bigint,
    updated_by      bigint,
    version         bigint        NOT NULL DEFAULT 0,
    CHECK (amount_refunded <= amount_paid),
    CHECK (discount_amount <= subtotal)
);
CREATE UNIQUE INDEX ux_invoices_subscription_live ON invoices (subscription_id) WHERE status <> 'VOID';
CREATE INDEX ix_invoices_member ON invoices (member_id, issued_at DESC);
CREATE INDEX ix_invoices_status_due ON invoices (status, due_date);
CREATE INDEX ix_invoices_branch_issued ON invoices (branch_id, issued_at);

CREATE TABLE invoice_lines (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  bigint        NOT NULL REFERENCES invoices (id) ON DELETE CASCADE,
    position    int           NOT NULL,
    line_type   varchar(30)   NOT NULL
        CHECK (line_type IN ('PLAN_FEE', 'JOINING_FEE', 'PRORATION_CREDIT')),
    description varchar(200)  NOT NULL,
    amount      numeric(12, 2) NOT NULL,     -- negative for credits
    UNIQUE (invoice_id, position)
);

CREATE TABLE payments (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id        bigint        NOT NULL REFERENCES invoices (id),
    member_id         bigint        NOT NULL REFERENCES members (id),
    amount            numeric(12, 2) NOT NULL CHECK (amount > 0),
    currency          varchar(3)       NOT NULL,
    method            varchar(20)   NOT NULL CHECK (method IN ('CASH', 'CARD', 'UPI', 'BANK_TRANSFER')),
    status            varchar(20)   NOT NULL
        CHECK (status IN ('SUCCEEDED', 'FAILED', 'PARTIALLY_REFUNDED', 'REFUNDED')),
    idempotency_key   varchar(100)  NOT NULL UNIQUE,
    request_hash      varchar(64)      NOT NULL,
    gateway_reference varchar(100),
    failure_reason    varchar(300),
    refunded_amount   numeric(12, 2) NOT NULL DEFAULT 0 CHECK (refunded_amount >= 0),
    processed_at      timestamptz   NOT NULL,
    received_by       bigint REFERENCES users (id),
    created_at        timestamptz   NOT NULL DEFAULT now(),
    updated_at        timestamptz   NOT NULL DEFAULT now(),
    created_by        bigint,
    updated_by        bigint,
    version           bigint        NOT NULL DEFAULT 0,
    CHECK (refunded_amount <= amount)
);
-- an invoice can be settled by exactly one successful payment (no partial payments)
CREATE UNIQUE INDEX ux_payments_invoice_settled ON payments (invoice_id)
    WHERE status IN ('SUCCEEDED', 'PARTIALLY_REFUNDED', 'REFUNDED');
CREATE INDEX ix_payments_member ON payments (member_id, processed_at DESC);
CREATE INDEX ix_payments_status_processed ON payments (status, processed_at);

CREATE TABLE refunds (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id        bigint        NOT NULL REFERENCES payments (id),
    amount            numeric(12, 2) NOT NULL CHECK (amount > 0),
    reason            varchar(300)  NOT NULL,
    status            varchar(20)   NOT NULL CHECK (status IN ('SUCCEEDED', 'FAILED')),
    gateway_reference varchar(100),
    idempotency_key   varchar(100)  UNIQUE,
    processed_by      bigint REFERENCES users (id),
    processed_at      timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX ix_refunds_payment ON refunds (payment_id);
CREATE INDEX ix_refunds_processed ON refunds (processed_at);

-- -------------------------------------------------------------------------------------
-- Attendance
-- -------------------------------------------------------------------------------------
CREATE TABLE attendance (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id         bigint      NOT NULL REFERENCES members (id),
    branch_id         bigint      NOT NULL REFERENCES gym_branches (id),
    subscription_id   bigint      NOT NULL REFERENCES subscriptions (id),
    check_in_time     timestamptz NOT NULL,
    check_out_time    timestamptz,
    check_in_method   varchar(20) NOT NULL CHECK (check_in_method IN ('FRONT_DESK', 'QR_CODE', 'MOBILE_APP')),
    checked_in_by     bigint REFERENCES users (id),
    auto_checked_out  boolean     NOT NULL DEFAULT false,
    created_at        timestamptz NOT NULL DEFAULT now(),
    CHECK (check_out_time IS NULL OR check_out_time >= check_in_time)
);
-- a member can have at most one open visit at any time, across all branches
CREATE UNIQUE INDEX ux_attendance_one_open_visit ON attendance (member_id) WHERE check_out_time IS NULL;
CREATE INDEX ix_attendance_branch_time ON attendance (branch_id, check_in_time);
CREATE INDEX ix_attendance_member_time ON attendance (member_id, check_in_time DESC);
CREATE INDEX ix_attendance_open ON attendance (check_in_time) WHERE check_out_time IS NULL;

-- -------------------------------------------------------------------------------------
-- Trainers
-- -------------------------------------------------------------------------------------
CREATE TABLE trainers (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             bigint        NOT NULL UNIQUE REFERENCES users (id),
    home_branch_id      bigint        NOT NULL REFERENCES gym_branches (id),
    employee_code       varchar(20)   NOT NULL UNIQUE,
    bio                 varchar(1000),
    certifications      varchar(500),
    years_of_experience int           NOT NULL DEFAULT 0 CHECK (years_of_experience >= 0),
    hourly_rate         numeric(10, 2) CHECK (hourly_rate IS NULL OR hourly_rate >= 0),
    max_active_clients  int           NOT NULL DEFAULT 20 CHECK (max_active_clients > 0),
    status              varchar(20)   NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'ON_LEAVE', 'INACTIVE')),
    created_at          timestamptz   NOT NULL DEFAULT now(),
    updated_at          timestamptz   NOT NULL DEFAULT now(),
    created_by          bigint,
    updated_by          bigint,
    deleted_at          timestamptz,
    version             bigint        NOT NULL DEFAULT 0
);
CREATE INDEX ix_trainers_branch ON trainers (home_branch_id) WHERE deleted_at IS NULL;

CREATE TABLE trainer_specializations (
    trainer_id     bigint      NOT NULL REFERENCES trainers (id) ON DELETE CASCADE,
    specialization varchar(50) NOT NULL,
    PRIMARY KEY (trainer_id, specialization)
);

CREATE TABLE trainer_availability (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id  bigint   NOT NULL REFERENCES trainers (id) ON DELETE CASCADE,
    branch_id   bigint   NOT NULL REFERENCES gym_branches (id),
    day_of_week smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),
    start_time  time     NOT NULL,
    end_time    time     NOT NULL,
    CHECK (start_time < end_time)
);
CREATE INDEX ix_trainer_availability ON trainer_availability (trainer_id, day_of_week);

CREATE TABLE member_trainers (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id   bigint       NOT NULL REFERENCES members (id),
    trainer_id  bigint       NOT NULL REFERENCES trainers (id),
    status      varchar(20)  NOT NULL CHECK (status IN ('ACTIVE', 'ENDED')),
    goal        varchar(300),
    assigned_at timestamptz  NOT NULL DEFAULT now(),
    ended_at    timestamptz,
    assigned_by bigint REFERENCES users (id),
    CHECK ((status = 'ENDED') = (ended_at IS NOT NULL))
);
CREATE UNIQUE INDEX ux_member_one_active_trainer ON member_trainers (member_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_member_trainers_trainer ON member_trainers (trainer_id, status);

CREATE TABLE training_sessions (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trainer_id bigint      NOT NULL REFERENCES trainers (id),
    member_id  bigint      NOT NULL REFERENCES members (id),
    branch_id  bigint      NOT NULL REFERENCES gym_branches (id),
    starts_at  timestamptz NOT NULL,
    ends_at    timestamptz NOT NULL,
    status     varchar(20) NOT NULL CHECK (status IN ('SCHEDULED', 'COMPLETED', 'CANCELLED', 'NO_SHOW')),
    notes      varchar(1000),
    created_at timestamptz NOT NULL DEFAULT now(),
    updated_at timestamptz NOT NULL DEFAULT now(),
    created_by bigint,
    updated_by bigint,
    version    bigint      NOT NULL DEFAULT 0,
    CHECK (ends_at > starts_at),
    CONSTRAINT ex_sessions_trainer_no_overlap EXCLUDE USING gist (
        trainer_id WITH =, tstzrange(starts_at, ends_at) WITH &&
    ) WHERE (status IN ('SCHEDULED', 'COMPLETED')),
    CONSTRAINT ex_sessions_member_no_overlap EXCLUDE USING gist (
        member_id WITH =, tstzrange(starts_at, ends_at) WITH &&
    ) WHERE (status IN ('SCHEDULED', 'COMPLETED'))
);
CREATE INDEX ix_sessions_trainer_start ON training_sessions (trainer_id, starts_at);
CREATE INDEX ix_sessions_member_start ON training_sessions (member_id, starts_at);

-- -------------------------------------------------------------------------------------
