CREATE UNIQUE INDEX ux_exercises_name ON exercises (lower(name));

CREATE TABLE workout_plans (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               varchar(120) NOT NULL,
    description        varchar(1000),
    goal               varchar(30)  NOT NULL
        CHECK (goal IN ('FAT_LOSS', 'MUSCLE_GAIN', 'STRENGTH', 'ENDURANCE', 'GENERAL_FITNESS', 'REHABILITATION')),
    difficulty         varchar(20)  NOT NULL CHECK (difficulty IN ('BEGINNER', 'INTERMEDIATE', 'ADVANCED')),
    duration_weeks     int          NOT NULL CHECK (duration_weeks BETWEEN 1 AND 52),
    template           boolean      NOT NULL,
    member_id          bigint REFERENCES members (id),
    trainer_id         bigint       NOT NULL REFERENCES trainers (id),
    source_template_id bigint REFERENCES workout_plans (id),
    status             varchar(20)  NOT NULL CHECK (status IN ('DRAFT', 'ACTIVE', 'COMPLETED', 'ARCHIVED')),
    start_date         date,
    end_date           date,
    trainer_notes      varchar(2000),
    created_at         timestamptz  NOT NULL DEFAULT now(),
    updated_at         timestamptz  NOT NULL DEFAULT now(),
    created_by         bigint,
    updated_by         bigint,
    version            bigint       NOT NULL DEFAULT 0,
    CHECK (template = (member_id IS NULL)),
    CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE UNIQUE INDEX ux_workout_one_active_per_member ON workout_plans (member_id) WHERE status = 'ACTIVE';
CREATE INDEX ix_workout_plans_trainer ON workout_plans (trainer_id, status);

CREATE TABLE workout_plan_exercises (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    workout_plan_id  bigint       NOT NULL REFERENCES workout_plans (id) ON DELETE CASCADE,
    exercise_id      bigint       NOT NULL REFERENCES exercises (id),
    day_number       smallint     NOT NULL CHECK (day_number BETWEEN 1 AND 7),
    position         int          NOT NULL,
    sets             int          NOT NULL CHECK (sets BETWEEN 1 AND 20),
    reps             int CHECK (reps IS NULL OR reps BETWEEN 1 AND 100),
    weight_kg        numeric(6, 2) CHECK (weight_kg IS NULL OR weight_kg >= 0),
    duration_seconds int CHECK (duration_seconds IS NULL OR duration_seconds > 0),
    rest_seconds     int CHECK (rest_seconds IS NULL OR rest_seconds >= 0),
    notes            varchar(300),
    UNIQUE (workout_plan_id, day_number, position),
    CHECK (reps IS NOT NULL OR duration_seconds IS NOT NULL)
);

CREATE TABLE member_progress (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id          bigint      NOT NULL REFERENCES members (id),
    workout_plan_id    bigint REFERENCES workout_plans (id),
    recorded_at        timestamptz NOT NULL,
    weight_kg          numeric(5, 2) CHECK (weight_kg IS NULL OR weight_kg BETWEEN 20 AND 400),
    body_fat_pct       numeric(4, 1) CHECK (body_fat_pct IS NULL OR body_fat_pct BETWEEN 2 AND 70),
    muscle_mass_kg     numeric(5, 2),
    chest_cm           numeric(5, 1),
    waist_cm           numeric(5, 1),
    hips_cm            numeric(5, 1),
    resting_heart_rate int CHECK (resting_heart_rate IS NULL OR resting_heart_rate BETWEEN 25 AND 220),
    notes              varchar(1000),
    recorded_by        bigint REFERENCES users (id),
    created_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ix_member_progress_member ON member_progress (member_id, recorded_at DESC);

-- -------------------------------------------------------------------------------------
-- Complaints & support
-- -------------------------------------------------------------------------------------
CREATE TABLE complaints (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticket_number     varchar(20)  NOT NULL UNIQUE,
    member_id         bigint REFERENCES members (id),
    branch_id         bigint       NOT NULL REFERENCES gym_branches (id),
    raised_by         bigint       NOT NULL REFERENCES users (id),
    category          varchar(20)  NOT NULL
        CHECK (category IN ('FACILITY', 'EQUIPMENT', 'STAFF', 'TRAINER', 'BILLING', 'HYGIENE', 'MEMBERSHIP', 'OTHER')),
    priority          varchar(20)  NOT NULL CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'CRITICAL')),
    status            varchar(20)  NOT NULL
        CHECK (status IN ('OPEN', 'IN_PROGRESS', 'ESCALATED', 'RESOLVED', 'CLOSED', 'REOPENED')),
    subject           varchar(200) NOT NULL,
    description       varchar(4000) NOT NULL,
    assigned_to       bigint REFERENCES users (id),
    resolution        varchar(4000),
    escalation_level  smallint     NOT NULL DEFAULT 0,
    sla_due_at        timestamptz  NOT NULL,
    first_response_at timestamptz,
    resolved_at       timestamptz,
    closed_at         timestamptz,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    updated_at        timestamptz  NOT NULL DEFAULT now(),
    created_by        bigint,
    updated_by        bigint,
    version           bigint       NOT NULL DEFAULT 0
);
CREATE INDEX ix_complaints_branch_status ON complaints (branch_id, status);
CREATE INDEX ix_complaints_assignee ON complaints (assigned_to, status);
CREATE INDEX ix_complaints_sla ON complaints (sla_due_at) WHERE status IN ('OPEN', 'IN_PROGRESS', 'REOPENED', 'ESCALATED');
CREATE INDEX ix_complaints_member ON complaints (member_id);

CREATE TABLE complaint_comments (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    complaint_id bigint        NOT NULL REFERENCES complaints (id) ON DELETE CASCADE,
    author_id    bigint        NOT NULL REFERENCES users (id),
    body         varchar(4000) NOT NULL,
    internal     boolean       NOT NULL DEFAULT false,   -- staff-only note, hidden from members
    created_at   timestamptz   NOT NULL DEFAULT now()
);
CREATE INDEX ix_complaint_comments ON complaint_comments (complaint_id, created_at);

-- -------------------------------------------------------------------------------------
-- Notifications (transactional outbox: rows are written in the business transaction and
-- delivered asynchronously by a dispatcher through pluggable channel senders)
-- -------------------------------------------------------------------------------------
CREATE TABLE notifications (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type              varchar(40)  NOT NULL,
    channel           varchar(20)  NOT NULL CHECK (channel IN ('IN_APP', 'EMAIL', 'SMS', 'PUSH')),
    recipient_user_id bigint REFERENCES users (id),
    member_id         bigint REFERENCES members (id),
    destination       varchar(254),            -- email address / phone number for external channels
    title             varchar(200) NOT NULL,
    body              varchar(2000) NOT NULL,
    status            varchar(20)  NOT NULL CHECK (status IN ('PENDING', 'SENT', 'FAILED')),
    dedup_key         varchar(150) UNIQUE,     -- prevents duplicate reminders from re-runs
    attempts          int          NOT NULL DEFAULT 0,
    next_attempt_at   timestamptz  NOT NULL DEFAULT now(),
    last_error        varchar(500),
    sent_at           timestamptz,
    read_at           timestamptz,
    created_at        timestamptz  NOT NULL DEFAULT now(),
    CHECK (recipient_user_id IS NOT NULL OR destination IS NOT NULL)
);
CREATE INDEX ix_notifications_dispatch ON notifications (next_attempt_at) WHERE status = 'PENDING';
CREATE INDEX ix_notifications_recipient ON notifications (recipient_user_id, created_at DESC);

-- -------------------------------------------------------------------------------------
-- Audit log (append-only)
-- -------------------------------------------------------------------------------------
CREATE TABLE audit_logs (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entity_type    varchar(40)  NOT NULL,
    entity_id      bigint       NOT NULL,
    action         varchar(40)  NOT NULL,
    actor_user_id  bigint,
    actor_email    varchar(254),
    member_id      bigint,
    branch_id      bigint,
    details        jsonb,
    correlation_id varchar(64),
    ip_address     varchar(64),
    occurred_at    timestamptz  NOT NULL DEFAULT now()
);
CREATE INDEX ix_audit_entity ON audit_logs (entity_type, entity_id, occurred_at DESC);
CREATE INDEX ix_audit_member ON audit_logs (member_id, occurred_at DESC) WHERE member_id IS NOT NULL;
CREATE INDEX ix_audit_actor ON audit_logs (actor_user_id, occurred_at DESC);

-- -------------------------------------------------------------------------------------
-- Distributed scheduler lock (ShedLock) so jobs run once across N application instances
-- -------------------------------------------------------------------------------------
CREATE TABLE shedlock (
    name       varchar(64)  PRIMARY KEY,
    lock_until timestamptz  NOT NULL,
    locked_at  timestamptz  NOT NULL,
    locked_by  varchar(255) NOT NULL
);
