-- =====================================================================================
-- GymOps core schema (PostgreSQL 15+)
--
-- Conventions
--   * bigint identity primary keys
--   * timestamptz for instants, date for business dates (business timezone), time for wall-clock
--   * money as numeric(12,2); currency as ISO-4217 code
--   * enum-like columns are varchar + CHECK constraints (portable, migration-friendly)
--   * soft deletion via deleted_at on master data (users, branches, members, trainers)
--   * optimistic locking via "version" on aggregates that are concurrently edited
--   * invariants that must hold under concurrency are enforced by the database
--     (exclusion constraints, partial unique indexes), not only by application code
-- =====================================================================================

CREATE EXTENSION IF NOT EXISTS btree_gist;

CREATE SEQUENCE member_code_seq START 1000;
CREATE SEQUENCE invoice_number_seq START 1;
CREATE SEQUENCE complaint_ticket_seq START 1;

-- -------------------------------------------------------------------------------------
-- Identity & access
-- -------------------------------------------------------------------------------------
CREATE TABLE roles (
    id   smallint PRIMARY KEY,
    name varchar(32) NOT NULL UNIQUE
);

CREATE TABLE users (
    id                    bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email                 varchar(254) NOT NULL,
    password_hash         varchar(120) NOT NULL,
    full_name             varchar(120) NOT NULL,
    phone                 varchar(20),
    status                varchar(20)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'LOCKED', 'DISABLED')),
    failed_login_attempts int          NOT NULL DEFAULT 0,
    locked_until          timestamptz,
    last_login_at         timestamptz,
    password_changed_at   timestamptz,
    created_at            timestamptz  NOT NULL DEFAULT now(),
    updated_at            timestamptz  NOT NULL DEFAULT now(),
    created_by            bigint,
    updated_by            bigint,
    deleted_at            timestamptz,
    version               bigint       NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_users_email_active ON users (lower(email)) WHERE deleted_at IS NULL;

CREATE TABLE user_roles (
    user_id bigint   NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    role_id smallint NOT NULL REFERENCES roles (id),
    PRIMARY KEY (user_id, role_id)
);

CREATE TABLE refresh_tokens (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash     varchar(64)    NOT NULL UNIQUE,           -- SHA-256 hex; raw token never stored
    family_id      uuid        NOT NULL,                  -- rotation chain, used for reuse detection
    expires_at     timestamptz NOT NULL,
    revoked_at     timestamptz,
    revoked_reason varchar(40),
    replaced_by_id bigint REFERENCES refresh_tokens (id),
    created_at     timestamptz NOT NULL DEFAULT now(),
    created_by_ip  varchar(64),
    user_agent     varchar(255)
);
CREATE INDEX ix_refresh_tokens_user ON refresh_tokens (user_id);
CREATE INDEX ix_refresh_tokens_family ON refresh_tokens (family_id);

-- -------------------------------------------------------------------------------------
-- Branches
-- -------------------------------------------------------------------------------------
CREATE TABLE gym_branches (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          varchar(20)  NOT NULL,
    name          varchar(120) NOT NULL,
    phone         varchar(20),
    email         varchar(254),
    address_line1 varchar(200) NOT NULL,
    address_line2 varchar(200),
    city          varchar(80)  NOT NULL,
    state         varchar(80),
    postal_code   varchar(20),
    country       varchar(2)   NOT NULL DEFAULT 'IN',
    timezone      varchar(64)  NOT NULL DEFAULT 'Asia/Kolkata',
    capacity      int          NOT NULL CHECK (capacity > 0),
    status        varchar(20)  NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'INACTIVE', 'UNDER_MAINTENANCE')),
    created_at    timestamptz  NOT NULL DEFAULT now(),
    updated_at    timestamptz  NOT NULL DEFAULT now(),
    created_by    bigint,
    updated_by    bigint,
    deleted_at    timestamptz,
    version       bigint       NOT NULL DEFAULT 0
);
CREATE UNIQUE INDEX ux_branches_code_active ON gym_branches (upper(code)) WHERE deleted_at IS NULL;

CREATE TABLE branch_operating_hours (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id   bigint   NOT NULL REFERENCES gym_branches (id) ON DELETE CASCADE,
    day_of_week smallint NOT NULL CHECK (day_of_week BETWEEN 1 AND 7),   -- ISO: 1 = Monday
    open_time   time,
    close_time  time,
    closed      boolean  NOT NULL DEFAULT false,
    UNIQUE (branch_id, day_of_week),
    CHECK (closed OR (open_time IS NOT NULL AND close_time IS NOT NULL AND open_time < close_time))
);

CREATE TABLE branch_facilities (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_id   bigint       NOT NULL REFERENCES gym_branches (id) ON DELETE CASCADE,
    name        varchar(80)  NOT NULL,
    description varchar(300),
    available   boolean      NOT NULL DEFAULT true
);
CREATE UNIQUE INDEX ux_branch_facility_name ON branch_facilities (branch_id, lower(name));

CREATE TABLE staff_branch_assignments (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    branch_id   bigint      NOT NULL REFERENCES gym_branches (id),
    assigned_at timestamptz NOT NULL DEFAULT now(),
    assigned_by bigint,
    UNIQUE (user_id, branch_id)
);
CREATE INDEX ix_staff_assignment_branch ON staff_branch_assignments (branch_id);

